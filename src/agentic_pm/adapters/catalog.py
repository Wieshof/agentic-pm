"""Tracker catalog and adapter capabilities.

`catalog.yaml` lists every tracker agentic-pm knows, what it can offer and how
far support is. Adapters declare `Capabilities`, so the engine can degrade
gracefully (e.g. no dependency data -> no risk propagation, only overdue checks).
"""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict

CATALOG_FILE = Path(__file__).with_name("catalog.yaml")

DependencySupport = Literal["native", "relation", "convention", "none"]
FieldSupport = Literal["native", "field", "none"]


class Capabilities(BaseModel):
    """What an adapter can actually deliver."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    dependencies: DependencySupport
    estimates: FieldSupport
    due_dates: FieldSupport
    multi_assignee: bool
    hierarchy: bool
    events: Literal["webhook", "polling"]
    writes: bool = False


class CatalogEntry(Capabilities):
    model_config = ConfigDict(frozen=True, extra="forbid")

    key: str
    name: str
    status: Literal["available", "planned", "candidate"]
    tier: Literal[1, 2, 3]
    api: str
    auth: str
    mcp: Literal["official", "community", "none"]
    verified: bool
    notes_en: str
    notes_de: str
    issue: int | None = None

    def capabilities(self, *, writes: bool = False) -> Capabilities:
        data = self.model_dump(include=set(Capabilities.model_fields))
        data["writes"] = writes
        return Capabilities(**data)


@lru_cache(maxsize=1)
def load_catalog() -> dict[str, CatalogEntry]:
    raw = yaml.safe_load(CATALOG_FILE.read_text(encoding="utf-8"))["trackers"]
    return {key: CatalogEntry(key=key, **entry) for key, entry in raw.items()}


# ---------------------------------------------------------------- rendering

NONE = "\u2014"  # em dash: not available
_SYMBOL = {
    "native": "✅",
    "relation": "🔗",
    "field": "🧩",
    "convention": "📝",
    "none": NONE,
    "webhook": "⚡",
    "polling": "🔄",
    "official": "✅",
    "community": "👥",
}
_HEAD = {
    "en": (
        "| Tracker | Status | Tier | Dependencies | Estimates | Due dates | Multi-assignee "
        "| Events | MCP | API · Auth | Notes |"
    ),
    "de": (
        "| Tracker | Status | Stufe | Abhängigkeiten | Schätzung | Fälligkeit | Mehrere Zuständige "
        "| Ereignisse | MCP | API · Auth | Hinweise |"
    ),
}
_STATUS = {
    "en": {"available": "✅ available", "planned": "🗓️ planned", "candidate": "💡 candidate"},
    "de": {"available": "✅ verfügbar", "planned": "🗓️ geplant", "candidate": "💡 Kandidat"},
}
_UNVERIFIED = {"en": "not yet verified live", "de": "noch nicht live geprüft"}
MATRIX_START = "<!-- tracker-matrix:start (generated by `agent-pm trackers --write-docs`) -->"
MATRIX_END = "<!-- tracker-matrix:end -->"


def render_matrix(lang: Literal["en", "de"], repo_url: str | None = None) -> str:
    rows = [_HEAD[lang], "|" + "---|" * 11]
    entries = sorted(
        load_catalog().values(), key=lambda e: (e.status != "available", e.tier, e.name)
    )
    for e in entries:
        status = _STATUS[lang][e.status]
        if e.issue is not None:
            status += (
                f" ([#{e.issue}]({repo_url}/issues/{e.issue}))" if repo_url else f" #{e.issue}"
            )
        note = e.notes_en if lang == "en" else e.notes_de
        if not e.verified:
            note += f" *({_UNVERIFIED[lang]})*"
        rows.append(
            f"| **{e.name}** | {status} | {e.tier} | {_SYMBOL[e.dependencies]} | "
            f"{_SYMBOL[e.estimates]} | {_SYMBOL[e.due_dates]} | "
            f"{'✅' if e.multi_assignee else NONE} | {_SYMBOL[e.events]} | {_SYMBOL[e.mcp]} | "
            f"{e.api} · {e.auth} | {note} |"
        )
    return "\n".join(rows)


def replace_matrix(doc: str, matrix: str) -> str:
    start, end = doc.index(MATRIX_START), doc.index(MATRIX_END)
    return doc[: start + len(MATRIX_START)] + "\n\n" + matrix + "\n\n" + doc[end:]
